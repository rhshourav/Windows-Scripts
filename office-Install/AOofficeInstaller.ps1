function Set-Theme {
    try {
        $h = $Host.UI.RawUI
        $h.BackgroundColor = 'Black'
        $h.ForegroundColor = 'White'
        $w = $h.WindowSize
        if ($w.Width -lt ($CON_W + 4)) { $w.Width = $CON_W + 4; $h.WindowSize = $w }
    } catch {}
    Clear-Host
}

function Write-C {
    param([string]$msg, [string]$col = 'White', [switch]$NoNewLine)
    if ($NoNewLine) { Write-Host $msg -ForegroundColor $col -NoNewline }
    else            { Write-Host $msg -ForegroundColor $col }
}
function Write-Div  { param([string]$c='-',[string]$col='DarkGray'); Write-C ($c * $CON_W) $col }
function Write-Step { param([string]$m); Write-C "  [>>] $m" 'Yellow'  }
function Write-OK   { param([string]$m); Write-C "  [OK] $m" 'Green'   }
function Write-Warn { param([string]$m); Write-C "  [!!] $m" 'Yellow'  }
function Write-Fail { param([string]$m); Write-C "  [XX] $m" 'Red'     }
function Write-Info { param([string]$m); Write-C "       $m" 'DarkGray'}

# ================================================================
#  PROGRESS BAR
#
#  All output lines are padded to exactly ($CON_W-1) chars before
#  being printed with \r.  This guarantees:
#    - No line wrap (which breaks \r-based overwriting)
#    - No leftover chars from a longer previous line
#
#  $Pct  0-100  = deterministic filled bar
#  $Pct  -1     = bouncing indeterminate block
# ================================================================
$script:Tick = 0

function Show-Bar {
    param([string]$Label, [int]$Pct, [string]$Info = '')

    $script:Tick++
    $BAR_W = 32   # inner bar width (short = safe on narrow terminals)

    $lbl = $Label.PadRight(18)
    if ($lbl.Length -gt 18) { $lbl = $lbl.Substring(0,18) }

    if ($Pct -lt 0) {
        $range = $BAR_W - 3
        # Bounce: 0..range..0
        $raw   = $script:Tick % ($range * 2)
        $pos   = if ($raw -le $range) { $raw } else { ($range * 2) - $raw }
        $inner = (' ' * $pos) + '[=]' + (' ' * ($range - $pos))
        $bar   = '|' + $inner + '|'
        $right = "  $Info"
    } else {
        $f     = [int][Math]::Round($Pct / 100 * $BAR_W)
        $e     = $BAR_W - $f
        $bar   = '|' + ([string][char]9608 * $f) + ([string][char]9617 * $e) + '|'
        $right = "  $Pct%  $Info"
    }

    $raw   = "  $lbl $bar$right"
    $maxL  = $CON_W - 1
    if ($raw.Length -gt $maxL) { $raw = $raw.Substring(0, $maxL) }
    $raw   = $raw.PadRight($maxL)

    Write-Host "`r$raw" -NoNewline -ForegroundColor Cyan
}

function Clear-Bar {
    Write-Host ("`r" + (' ' * ($CON_W - 1)) + "`r") -NoNewline
}

