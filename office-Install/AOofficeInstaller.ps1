            -Method Post -ContentType 'application/json' `
            -Body $body -TimeoutSec 5 -EA SilentlyContinue | Out-Null
    } catch {}
}

# ================================================================
#  DOWNLOAD — BITS (real %) with IWR fallback
#  No WebClient async: avoids closure scope bugs entirely
# ================================================================
function Get-FileProgress {
    param([string]$Url, [string]$Dest, [string]$Label)

    try {
        Import-Module BitsTransfer -EA Stop
        $job = Start-BitsTransfer -Source $Url -Destination $Dest -Asynchronous -EA Stop

        while ($job.JobState -notin @('Transferred','Error','TransientError')) {
            $tot  = $job.BytesTotal
            $recv = $job.BytesTransferred
            if ($tot -gt 0) {
                Show-Bar $Label ([int]($recv / $tot * 100)) ("{0:N1}/{1:N1} MB" -f ($recv/1MB),($tot/1MB))
            } else {
                Show-Bar $Label -1 "connecting..."
            }
            Start-Sleep -Milliseconds 300
        }

        if ($job.JobState -eq 'Transferred') {
            Complete-BitsTransfer -BitsJob $job -EA SilentlyContinue
            Clear-Bar; return
        }
        Remove-BitsTransfer -BitsJob $job -EA SilentlyContinue
    } catch {}

    # Fallback: synchronous IWR — no live %, but always works
    Show-Bar $Label -1 "downloading..."
    try {
        Invoke-WebRequest -Uri $Url -OutFile $Dest -UseBasicParsing -EA Stop
    } catch {
        Clear-Bar; throw "Download failed: $_"
    }
    Clear-Bar
}

# ================================================================
#  WAIT FOR A PROCESS + ALL ITS NAMED CHILD PROCESSES
#
#  ODT /configure starts setup.exe, which spawns OfficeC2RClient.exe
#  (the actual installer). If we only wait for setup.exe we return
#  while installation is still running in the background.
#
#  Strategy:
#    1. Wait for the direct process ($Proc) to exit.
#    2. Then wait for any OfficeC2RClient / OfficeClickToRun children
#       to also finish — these are the real installers.
#    3. Time-box the child wait at 45 minutes to avoid infinite hang.
# ================================================================
function Wait-OdtComplete {
    param([System.Diagnostics.Process]$Proc, [string]$WorkDir, [string]$Label)

    $officeDir = Join-Path $WorkDir "Office"
    $spinChars = '|/-\'
    $tick      = 0
    $lastMB    = 0
    $stuckFor  = 0

    # ---- Phase A: wait for setup.exe /configure ----
    do {
        try { $Proc.Refresh() } catch {}
        $tick++

        # Measure Office folder size growth as download proxy
        $sizeMB = 0
        if (Test-Path $officeDir) {
            try {
                $sizeMB = [int](
                    (Get-ChildItem $officeDir -Recurse -File -EA SilentlyContinue |
                     Measure-Object -Property Length -Sum -EA SilentlyContinue).Sum / 1MB
                )
            } catch {}
        }

        if ($sizeMB -ne $lastMB) { $stuckFor = 0; $lastMB = $sizeMB } else { $stuckFor++ }

        $spin = $spinChars[$tick % 4]
        # Rough target: ~2000 MB for M365, cap at 98% while running
        $pct  = [Math]::Min(98, [int]($sizeMB / 2000 * 100))

        if ($stuckFor -gt 15) {
            Show-Bar $Label -1 "$spin installing..."
        } else {
            Show-Bar $Label $pct "$spin ${sizeMB} MB"
        }

        Start-Sleep -Seconds 3

    } while (-not $Proc.HasExited)

    # ---- Phase B: wait for OfficeC2RClient / OfficeClickToRun children ----
    # These processes do the actual disk write after setup.exe exits.
    $childNames  = @('OfficeC2RClient','OfficeClickToRun','setup')
    $deadlineMin = 45
    $waited      = 0

    do {
        $children = @(Get-Process -Name $childNames -EA SilentlyContinue |
                      Where-Object { -not $_.HasExited })

        if ($children.Count -eq 0) { break }

        $waited++
        if ($waited -gt ($deadlineMin * 4)) {   # 4 checks/min (every 15s)
            Write-C ""
            Write-Warn "Timed out waiting for Office background processes. Install may still be running."
            break
        }

        $tick++
        $spin = $spinChars[$tick % 4]
        Show-Bar $Label -1 "$spin finalizing... (${waited}s)"
        Start-Sleep -Seconds 15

    } while ($true)

    Clear-Bar
}

# ================================================================
#  WATCH ODT /download (manifests — fast phase)
# ================================================================
function Watch-OdtDownload {
    param([System.Diagnostics.Process]$Proc, [string]$OfficeDir, [string]$Label)

    $lastCount = 0
    do {
        try { $Proc.Refresh() } catch {}
        $count = 0
        if (Test-Path $OfficeDir) {
            $count = @(Get-ChildItem $OfficeDir -Recurse -File -EA SilentlyContinue).Count
        }
        $lastCount = $count
        Show-Bar $Label ([Math]::Min(99, $count * 8)) "$count files"
        Start-Sleep -Seconds 2
    } while (-not $Proc.HasExited)
    Clear-Bar
}

