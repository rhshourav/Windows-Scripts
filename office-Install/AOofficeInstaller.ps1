# ================================================================
#  INSTALL ONE PACKAGE
# ================================================================
function Install-Package { param($pkg)

    $uid     = ([Guid]::NewGuid().ToString('N')).Substring(0,6)
    $workDir = Join-Path $env:TEMP "OfficeInstall_$($pkg.Short)_$uid"
    $zipPath = Join-Path $workDir $pkg.ZipName
    $xmlPath = Join-Path $workDir "Install_$($pkg.Short).xml"

    Write-C ""
    Write-Div '-' 'DarkCyan'
    Write-C "  Package  : $($pkg.Name)" 'Cyan'
    Write-C "  WorkDir  : $workDir" 'DarkGray'
    Write-Div '-' 'DarkCyan'
    Write-C ""

    Send-Telemetry $pkg

    $ok = $false
    try {

        # 1. Working directory
        New-Item -ItemType Directory -Path $workDir -Force -EA Stop | Out-Null
        Write-Step "Work directory created."

        # 2. Write our own XML (ignore whatever XML is in the ZIP)
        #    This is the fix for exit code 17002.
        Set-Content -LiteralPath $xmlPath -Value $pkg.ConfigXml -Encoding UTF8 -EA Stop
        Write-OK "Configuration XML written."
        Write-Info "Config : $xmlPath"

        # 3. Download ZIP (we only need setup.exe from it)
        Write-Step "Downloading ODT package..."
        Enable-Tls
        Get-FileProgress -Url $pkg.ZipUrl -Dest $zipPath -Label "Get ZIP"
        if (-not (Test-Path $zipPath)) { throw "ZIP missing after download. URL: $($pkg.ZipUrl)" }
        Write-OK ("Downloaded  ({0:N1} MB)" -f ((Get-Item $zipPath).Length / 1MB))

        # 4. Extract
        Write-Step "Extracting..."
        try { Expand-Archive -Path $zipPath -DestinationPath $workDir -Force -EA Stop }
        catch { throw "Extraction failed: $_" }
        Write-OK "Extracted."

        # 5. Locate setup.exe
        $setupExe = Get-ChildItem $workDir -Recurse -Filter 'setup.exe' -File -EA SilentlyContinue |
                    Select-Object -First 1
        if (-not $setupExe) { throw "setup.exe not found in ZIP." }
        Write-Info "Setup  : $($setupExe.FullName)"

        # ----------------------------------------------------------------
        # 6. ODT /download
        #    Downloads small manifest / CAB index files only (~8-20 files).
        #    Completes in seconds.  8 files = NORMAL / DONE.
        # ----------------------------------------------------------------
        Write-C ""
        Write-Step "Phase 1/2 — Fetching manifests..."
        Write-Info "Downloads index files only. Completes in seconds."
        Write-C ""

        $officeDir = Join-Path $workDir "Office"

        $dlProc = Start-Process `
            -FilePath         $setupExe.FullName `
            -ArgumentList     "/download `"$xmlPath`"" `
            -WorkingDirectory $workDir `
            -PassThru -EA Stop

        if ($null -eq $dlProc) { throw "Failed to launch ODT /download." }

        Watch-OdtDownload -Proc $dlProc -OfficeDir $officeDir -Label "Manifests"

        try { $dlProc.Refresh() } catch {}
        if ($dlProc.ExitCode -ne 0) {
            throw "ODT /download failed with exit code $($dlProc.ExitCode)."
        }
        Write-OK "Manifests ready."

        # ----------------------------------------------------------------
        # 7. ODT /configure
        #    Downloads 1-3 GB AND installs.  setup.exe may exit before
        #    OfficeC2RClient.exe finishes — we wait for both.
        # ----------------------------------------------------------------
        Write-C ""
        Write-Step "Phase 2/2 — Downloading + Installing Office..."
        Write-Info "Downloads 1-3 GB from Microsoft. May take 5-30 minutes."
        Write-Info "Do NOT close this window."
        Write-C ""

        $instProc = Start-Process `
            -FilePath         $setupExe.FullName `
            -ArgumentList     "/configure `"$xmlPath`"" `
            -WorkingDirectory $workDir `
            -PassThru -EA Stop

        if ($null -eq $instProc) { throw "Failed to launch ODT /configure." }

        Wait-OdtComplete -Proc $instProc -WorkDir $workDir -Label "Download+Install"

        try { $instProc.Refresh() } catch {}
        if ($instProc.ExitCode -notin @(0, $null)) {
            throw "ODT /configure failed. Exit code: $($instProc.ExitCode). Check: $env:TEMP\USL-*.log"
        }
        Write-OK "Installer finished."

        # 8. Verify
        if (Test-OfficePresent) {
            Write-OK "WINWORD.EXE confirmed on disk."
        } else {
            Write-Warn "WINWORD.EXE not found in default path."
            Write-Info "Office may still be finishing up. Launch Word in a minute to verify."
        }

        $ok = $true

    } catch {
        Write-C ""
        Write-Fail "Failed : $($pkg.Name)"
        Write-Fail "Reason : $_"
        Write-Warn "Skipping to next package."
    } finally {
        try {
            if (Test-Path $workDir) {
                Write-C ""; Write-Step "Cleaning up temp files..."
                Remove-Item -LiteralPath $workDir -Recurse -Force -EA SilentlyContinue
                Write-OK "Temp files removed."
            }
        } catch {}
    }

    return $ok
}

# ================================================================
#  MENU
# ================================================================
function Show-Menu {
    Write-C "  Available Packages" 'White'; Write-C ""
    foreach ($p in $PACKAGES) { Write-C ("  [{0}]  {1}" -f $p.Id, $p.Name) 'Yellow' }
    Write-C ""
    Write-C "  [A]  Install ALL packages" 'Green'
    Write-C "  [Q]  Quit" 'Red'
    Write-C ""; Write-Div '-' 'DarkGray'; Write-C ""
    Write-C "  Separate multiple choices with commas  (e.g.  1,2  or  A)" 'DarkGray'
    Write-C ""
    Write-C "  > " 'Cyan' -NoNewLine
}

function Resolve-Selection { param([string]$raw)
    $raw = $raw.Trim()
    if ($raw -match '^[Qq]$') { return 'QUIT' }
    if ($raw -match '^[Aa]$') { return $PACKAGES }
    $sel = [System.Collections.Generic.List[object]]::new()
    foreach ($tok in ($raw -split ',')) {
        $tok = $tok.Trim(); $id = 0
        if ([int]::TryParse($tok,[ref]$id)) {
            $m = $PACKAGES | Where-Object { $_.Id -eq $id }
            if ($m) { $sel.Add($m) } else { Write-Warn "Unknown option '$tok' — ignored." }
        }
    }
    return $sel
}

